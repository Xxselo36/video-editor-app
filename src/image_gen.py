    def __init__(self, model_id: str = None, device: str = None):
        """
        Initialisiert den Bildgenerator.

        Args:
            model_id: Hugging Face Model ID (None = Auto-Auswahl)
            device: "cuda", "mps", oder "cpu" (None = Auto-Detect)
        """
        self.model_id = model_id
        self.device = device
        self.pipe = None
        self._initialized = False

        if not DIFFUSERS_AVAILABLE:
            print("    WARNUNG: diffusers nicht verfügbar!")
            print("    Installiere: pip install diffusers torch accelerate transformers")
            return

    def _detect_device(self) -> str:
        """Erkennt das beste verfügbare Device."""
        if torch.cuda.is_available():
            return "cuda"
        elif hasattr(torch.backends, 'mps') and torch.backends.mps.is_available():
            return "mps"  # Apple Silicon
        else:
            return "cpu"

    def _initialize(self):
        """Lazy-Initialisierung des Modells."""
        if self._initialized or not DIFFUSERS_AVAILABLE:
            return

        print("    Initialisiere Stable Diffusion...")

        # Device erkennen
        if self.device is None:
            self.device = self._detect_device()
        print(f"      Device: {self.device}")

        # Modell auswählen
        if self.model_id is None:
            # SD-Turbo für schnelle Generierung
            self.model_id = self.DEFAULT_MODEL

        print(f"      Modell: {self.model_id}")
        print("      (Erster Start lädt ~2-4GB Modell-Daten)")

        try:
            # Pipeline laden
            if self.device == "cuda":
                # GPU: float16 für Speicherersparnis
                self.pipe = StableDiffusionPipeline.from_pretrained(
                    self.model_id,
                    torch_dtype=torch.float16,
                    variant="fp16" if "turbo" not in self.model_id else None,
                    safety_checker=None,  # Für Geschwindigkeit
                )
                self.pipe = self.pipe.to("cuda")
                # Speicher-Optimierungen
                self.pipe.enable_attention_slicing()
                if hasattr(self.pipe, 'enable_xformers_memory_efficient_attention'):
                    try:
                        self.pipe.enable_xformers_memory_efficient_attention()
                    except Exception:
                        pass

            elif self.device == "mps":
                # Apple Silicon
                self.pipe = StableDiffusionPipeline.from_pretrained(
                    self.model_id,
                    torch_dtype=torch.float32,
                    safety_checker=None,
                )
                self.pipe = self.pipe.to("mps")

            else:
                # CPU (langsam)
                print("      WARNUNG: CPU-Modus ist langsam!")
                self.pipe = StableDiffusionPipeline.from_pretrained(
                    self.model_id,
                    torch_dtype=torch.float32,
                    safety_checker=None,
                )

            # Schnellerer Scheduler
            self.pipe.scheduler = DPMSolverMultistepScheduler.from_config(
                self.pipe.scheduler.config
            )

            self._initialized = True
            print("      ✅ Stable Diffusion bereit!")

        except Exception as e:
            print(f"      ❌ Fehler beim Laden: {e}")
            print("      Versuche Fallback-Modell...")
            try:
                self.pipe = StableDiffusionPipeline.from_pretrained(
                    self.FALLBACK_MODEL,
                    torch_dtype=torch.float32,
                    safety_checker=None,
                )
                if self.device != "cpu":
                    self.pipe = self.pipe.to(self.device)
                self._initialized = True
            except Exception as e2:
                print(f"      ❌ Auch Fallback fehlgeschlagen: {e2}")

    def is_available(self) -> bool:
        """Prüft ob Bildgenerierung verfügbar ist."""
        return DIFFUSERS_AVAILABLE

    def generate(self, prompt: str, width: int = 512, height: int = 512,
                 num_inference_steps: int = 20, guidance_scale: float = 7.5) -> Optional[np.ndarray]:
        """
        Generiert ein Bild.

        Args:
            prompt: Beschreibung des Bildes
            width: Bildbreite (512 empfohlen für Geschwindigkeit)
            height: Bildhöhe
            num_inference_steps: Anzahl der Schritte (4 für SD-Turbo, 20-30 für andere)
            guidance_scale: CFG Scale (0 für SD-Turbo, 7.5 für andere)

        Returns:
            RGB numpy array oder None bei Fehler
        """
        if not self.is_available():
            return None

        self._initialize()

        if self.pipe is None:
            return None

        try:
            # Für SD-Turbo: wenige Steps, kein CFG
            if "turbo" in self.model_id.lower():
                num_inference_steps = min(num_inference_steps, 4)
                guidance_scale = 0.0

            # Generieren
            with torch.no_grad():
                result = self.pipe(
                    prompt,
                    width=width,
                    height=height,
                    num_inference_steps=num_inference_steps,
                    guidance_scale=guidance_scale,
                )

            # Zu numpy konvertieren
            image = result.images[0]
            return np.array(image)

        except Exception as e:
            print(f"      Generierung fehlgeschlagen: {e}")
            return None

    def generate_for_keyword(self, keyword: str, width: int = 512,
                             height: int = 512) -> Optional[np.ndarray]:
        """
        Generiert ein Bild basierend auf einem Keyword.

        Args:
            keyword: Das Keyword (z.B. "auto", "strand")
            width: Bildbreite
            height: Bildhöhe

        Returns:
            RGB numpy array oder None
        """
        keyword_lower = keyword.lower().strip()

        # Prompt für Keyword finden
        prompt = self.KEYWORD_PROMPTS.get(keyword_lower)

        if prompt is None:
            # Fallback: Generisches Prompt mit dem Keyword
            prompt = f"a beautiful image of {keyword}, photorealistic, high quality"

        print(f"      Generiere Bild für '{keyword}'...")
        return self.generate(prompt, width, height)

    def generate_images_for_subtitles(self, subtitles: list,
                                       keywords: List[str] = None,
                                       video_size: Tuple[int, int] = (1080, 1920),
                                       max_images: int = 5) -> List[GeneratedImage]:
        """
        Generiert Bilder basierend auf Keywords in Untertiteln.

        Args:
            subtitles: Liste von Subtitle-Objekten mit start, end, text
            keywords: Liste von Keywords die Bilder triggern (None = alle bekannten)
            video_size: (width, height) des Videos
            max_images: Maximale Anzahl zu generierender Bilder

        Returns:
            Liste von GeneratedImage Objekten
        """
        if not self.is_available():
            return []

        # Keywords die wir suchen (nur lange genug und nicht auf Blacklist)
        if keywords is None:
            keywords = [k for k in self.KEYWORD_PROMPTS.keys()
                       if len(k) >= self.MIN_KEYWORD_LENGTH
                       and k.lower() not in self.KEYWORD_BLACKLIST]

        keywords_lower = [k.lower() for k in keywords
                         if k.lower() not in self.KEYWORD_BLACKLIST]

        # Finde Keywords in Untertiteln (nur ganze Wörter!)
        found_keywords = []
        for sub in subtitles:
            text_lower = sub.text.lower()
            for kw in keywords_lower:
                # Regex für ganzes Wort (nicht "om" in "kommen")
                pattern = r'\b' + re.escape(kw) + r'\b'
                if re.search(pattern, text_lower) and len(found_keywords) < max_images:
                    # Vermeiden von Duplikaten (gleiches Keyword nochmal)
                    if not any(f[0] == kw for f in found_keywords):
                        found_keywords.append((kw, sub.start, sub.end))

        if not found_keywords:
            print("      Keine passenden Keywords für Bildgenerierung gefunden")
            print("      (Tipp: Verwende konkrete Wörter wie 'Strand', 'Auto', 'Pizza')")
            return []

        print(f"      {len(found_keywords)} Keywords gefunden: {[f[0] for f in found_keywords]}")

        # Bilder generieren im 9:16 Format für TikTok/Reels
        # SD-kompatible Größe: 576x1024 (9:16 Verhältnis)
        vid_w, vid_h = video_size
        if vid_h > vid_w:  # Hochformat (9:16)
            img_w, img_h = 576, 1024
        else:  # Querformat (16:9)
            img_w, img_h = 1024, 576

        generated = []
        for keyword, start_time, end_time in found_keywords:
            image = self.generate_for_keyword(keyword, img_w, img_h)

            if image is not None:
                generated.append(GeneratedImage(
                    image=image,
                    prompt=self.KEYWORD_PROMPTS.get(keyword, keyword),
                    keyword=keyword,
                    timestamp=start_time,
                    duration=min(3.0, end_time - start_time + 1.0)  # Max 3 Sekunden
                ))

        return generated

    def close(self):
        """Gibt Ressourcen frei."""
        if self.pipe is not None:
            del self.pipe
            self.pipe = None
            if torch.cuda.is_available():
                torch.cuda.empty_cache()


