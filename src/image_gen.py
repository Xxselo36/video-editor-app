def detect_image_keywords(text: str, custom_keywords: List[str] = None) -> List[str]:
    """
    Erkennt Keywords für Bildgenerierung in einem Text.

    Args:
        text: Der zu analysierende Text
        custom_keywords: Zusätzliche Keywords

    Returns:
        Liste gefundener Keywords
    """
    # Nur Keywords mit Mindestlänge und nicht auf Blacklist
    all_keywords = [k for k in ImageGenerator.KEYWORD_PROMPTS.keys()
                   if len(k) >= ImageGenerator.MIN_KEYWORD_LENGTH
                   and k.lower() not in ImageGenerator.KEYWORD_BLACKLIST]
    if custom_keywords:
        all_keywords.extend([k for k in custom_keywords
                           if len(k) >= ImageGenerator.MIN_KEYWORD_LENGTH
                           and k.lower() not in ImageGenerator.KEYWORD_BLACKLIST])

    text_lower = text.lower()
    found = []

    for kw in all_keywords:
        # Nur ganze Wörter matchen
        pattern = r'\b' + re.escape(kw) + r'\b'
        if re.search(pattern, text_lower):
            found.append(kw)

    return found


